import zipfile
import io

def load_file(uploaded_file):
    """Load CSV directly or extract CSV from ZIP."""
    if uploaded_file is None:
        return None

    filename = uploaded_file.name.lower()

    # --- CASE 1: CSV directly uploaded ---
    if filename.endswith(".csv"):
        try:
            return pd.read_csv(uploaded_file, low_memory=True, on_bad_lines="skip")
        except Exception as e:
            st.error(f"❌ Error reading CSV: {e}")
            return None

    # --- CASE 2: ZIP uploaded ---
    if filename.endswith(".zip"):
        try:
            z = zipfile.ZipFile(uploaded_file)
            files_inside = z.namelist()

            # Find first CSV inside ZIP
            csv_files = [f for f in files_inside if f.lower().endswith(".csv")]

            if len(csv_files) == 0:
                st.error("❌ ZIP file contains no CSV.")
                return None

            csv_to_read = csv_files[0]
            st.success(f"📄 Found CSV inside ZIP: {csv_to_read}")

            with z.open(csv_to_read) as f:
                return pd.read_csv(f, low_memory=True, on_bad_lines="skip")

        except Exception as e:
            st.error(f"❌ Error reading ZIP: {e}")
            return None

    st.error("❌ Unsupported file type. Upload CSV or ZIP.")
    return None

